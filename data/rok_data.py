def buscar_comandante(query: str):
    q = query.lower().strip()
    if q in COMANDANTES:
        return q, COMANDANTES[q]
    for key, val in COMANDANTES.items():
        if q in key or q in val["nombre"].lower():
            return key, val
        if any(q in alias for alias in val.get("alias", [])):
            return key, val
    # Búsqueda parcial más permisiva
    for key, val in COMANDANTES.items():
        if any(q in parte for parte in key.split()):
            return key, val
    return None, None


